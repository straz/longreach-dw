// vendor/ty-core/{schema.pg,five_questions.gq,decision_watch.gq}, a copy of tyapi's ty-core model,
// → src/model/generated.ts: the row type of every stored query dw reads (docs/PLAN.md §5, phase 1).
//
//   node scripts/gen-model.ts           write the file
//   node scripts/gen-model.ts --check   fail if the file is not what this would write
//
// The check runs first in `pnpm build`, so model types cannot drift from the vendored copy.

import { readFileSync, writeFileSync } from 'node:fs'
import { type Field, type FieldType, parseQueries, parseSchema } from './tycore.ts'

const root = new URL('../', import.meta.url)
const read = (path: string) => readFileSync(new URL(path, root), 'utf8')
const OUT = 'src/model/generated.ts'

const pascal = (s: string) => s.replace(/(^|_)(\w)/g, (_, __, c: string) => c.toUpperCase())

function tsType(t: FieldType, enumName?: string): string {
  if (t.kind === 'list') return 'string[]'
  if (t.kind === 'enum') return enumName ?? t.values.map((v) => `'${v}'`).join(' | ')
  switch (t.name) {
    case 'String':
      return 'string'
    case 'Bool':
      return 'boolean'
    case 'DateTime':
      return 'IsoDateTime'
    case 'Date':
      return 'IsoDate'
    case 'F64':
    case 'I32':
      return 'number'
  }
}

export type Inputs = { schema: string; queryFiles: Record<string, string> }

export function generate(inputs: Inputs): string {
  const schema = parseSchema(inputs.schema)
  const queries = Object.entries(inputs.queryFiles).flatMap(([file, src]) => parseQueries(src, schema).map((q) => ({ ...q, file })))
  const clash = queries.find((q, i) => queries.findIndex((o) => o.name === q.name) !== i)
  if (clash) throw new Error(`${clash.file} redefines ${clash.name}`)
  const lines: string[] = [
    '// Generated by scripts/gen-model.ts from vendor/ty-core/ (tyapi\'s ty-core model). Do not edit.',
    '// Regenerate with `pnpm gen:model`.',
    '',
    '/** An ISO-8601 instant in UTC, as the API writes it: 2027-03-31T10:00Z (tyapi docs/18-dw-backend.md, W14). */',
    'export type IsoDateTime = string',
    '/** A calendar day, YYYY-MM-DD: what dw works out from an instant for display and as-of controls. */',
    'export type IsoDate = string',
    '',
  ]

  // Enums get a named type and a runtime list, so validators and pickers share them.
  const enumNames = new Map<string, string>()
  const fieldLine = (owner: string, f: Field) => {
    const doc = f.description ? `  /** ${f.description.replace(/\*\//g, '* /')} */\n` : ''
    const t = tsType(f.type, enumNames.get(`${owner}.${f.name}`))
    return `${doc}  ${f.name}${f.optional ? '?' : ''}: ${t}`
  }
  for (const def of [...schema.nodes, ...schema.edges]) {
    for (const f of def.fields) {
      if (f.type.kind !== 'enum') continue
      const name = `${def.name}${pascal(f.name)}`
      enumNames.set(`${def.name}.${f.name}`, name)
      const values = f.type.values.map((v) => `'${v}'`).join(', ')
      lines.push(`export const ${lowerConst(name)} = [${values}] as const`)
      lines.push(`export type ${name} = (typeof ${lowerConst(name)})[number]`)
    }
  }
  lines.push('')

  for (const n of schema.nodes) {
    if (n.description) lines.push(`/** ${n.description} */`)
    lines.push(`export interface ${n.name} {`, ...n.fields.map((f) => fieldLine(n.name, f)), '}', '')
  }
  for (const e of schema.edges) {
    lines.push(`/** ${e.from} → ${e.to} */`)
    lines.push(`export interface ${e.name}Data {`, ...e.fields.map((f) => fieldLine(e.name, f)), '}', '')
  }

  lines.push(`export const nodeTypes = [${schema.nodes.map((n) => `'${n.name}'`).join(', ')}] as const`)
  lines.push('export type NodeType = (typeof nodeTypes)[number]', '')
  lines.push('export const edgeEndpoints = {')
  for (const e of schema.edges) lines.push(`  ${e.name}: { from: '${e.from}', to: '${e.to}' },`)
  lines.push('} as const satisfies Record<string, { from: NodeType; to: NodeType }>')
  lines.push('export type EdgeType = keyof typeof edgeEndpoints', '')

  // Runtime field specs, for validators: 'String', 'Date?', 'enum:CommitmentState', ...
  const spec = (owner: string, f: Field) => {
    const base = f.type.kind === 'enum' ? `enum:${enumNames.get(`${owner}.${f.name}`)}` : f.type.kind === 'list' ? '[String]' : f.type.name
    return `${f.name}: '${base}${f.optional ? '?' : ''}'`
  }
  lines.push('export type FieldSpec = string')
  lines.push('export const nodeFields: Record<NodeType, Record<string, FieldSpec>> = {')
  for (const n of schema.nodes) lines.push(`  ${n.name}: { ${n.fields.map((f) => spec(n.name, f)).join(', ')} },`)
  lines.push('}')
  lines.push('export const edgeFields: Record<EdgeType, Record<string, FieldSpec>> = {')
  for (const e of schema.edges) lines.push(`  ${e.name}: { ${e.fields.map((f) => spec(e.name, f)).join(', ')} },`)
  lines.push('}')
  lines.push('export const enumValues: Record<string, readonly string[]> = {')
  for (const name of enumNames.values()) lines.push(`  ${name}: ${lowerConst(name)},`)
  lines.push('}', '')

  lines.push('export interface NodeData {')
  for (const n of schema.nodes) lines.push(`  ${n.name}: ${n.name}`)
  lines.push('}', 'export interface EdgeData {')
  for (const e of schema.edges) lines.push(`  ${e.name}: ${e.name}Data`)
  lines.push('}', '')
  lines.push('/** One line of a ty-core JSONL seed or load payload. Edge ends are node slugs. */')
  lines.push('export type TyRecord =')
  lines.push('  | { [T in NodeType]: { type: T; data: NodeData[T] } }[NodeType]')
  lines.push('  | { [E in EdgeType]: { edge: E; from: string; to: string; data?: EdgeData[E] } }[EdgeType]', '')

  lines.push('/** Every stored query of the model: five_questions.gq, then decision_watch.gq. */')
  lines.push('export interface QueryCatalog {')
  for (const q of queries) {
    if (q.description) lines.push(`  /** ${q.description} */`)
    const params = q.params.length ? `{ ${q.params.map((p) => `${p.name}${p.optional ? '?' : ''}: ${tsType(p.type)}`).join('; ')} }` : 'Record<string, never>'
    const cols = q.columns
      .map((c) => `${c.name}${c.optional ? '?' : ''}: ${tsType(c.type, enumNames.get(`${c.from.type}.${c.from.field}`))}`)
      .join('; ')
    lines.push(`  ${q.name}: { params: ${params}; row: { ${cols} } }`)
  }
  lines.push('}', '')
  lines.push(`export const queryNames = [${queries.map((q) => `'${q.name}'`).join(', ')}] as const satisfies readonly (keyof QueryCatalog)[]`)
  lines.push('export type QueryName = keyof QueryCatalog')
  lines.push("export type QueryParams<N extends QueryName> = QueryCatalog[N]['params']")
  lines.push("export type QueryRow<N extends QueryName> = QueryCatalog[N]['row']")
  lines.push('/** Each query\'s parameter names, for contract tests. */')
  lines.push('export const queryParamNames: Record<QueryName, readonly string[]> = {')
  for (const q of queries) lines.push(`  ${q.name}: [${q.params.map((p) => `'${p.name}'`).join(', ')}],`)
  lines.push('}')
  lines.push('/** Each query\'s result columns, for contract tests. */')
  lines.push('export const queryColumns: Record<QueryName, readonly string[]> = {')
  for (const q of queries) lines.push(`  ${q.name}: [${q.columns.map((c) => `'${c.name}'`).join(', ')}],`)
  lines.push('}')
  return lines.join('\n')
}

function lowerConst(typeName: string): string {
  return typeName[0].toLowerCase() + typeName.slice(1) + 'Values'
}

const isMain = process.argv[1] && import.meta.url === new URL(`file://${process.argv[1]}`).href
if (isMain) {
  const next = generate({
    schema: read('vendor/ty-core/schema.pg'),
    queryFiles: Object.fromEntries(['five_questions.gq', 'decision_watch.gq'].map((f) => [f, read(`vendor/ty-core/${f}`)])),
  })
  if (process.argv.includes('--check')) {
    let current = ''
    try {
      current = read(OUT)
    } catch {
      // Missing file: reported below as stale.
    }
    if (current !== next) {
      console.error(`${OUT} is stale: run \`pnpm gen:model\` and commit the result.`)
      process.exit(1)
    }
    console.log(`${OUT} is current.`)
  } else {
    writeFileSync(new URL(OUT, root), next)
    console.log(`Wrote ${OUT}.`)
  }
}
