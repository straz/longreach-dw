// vendor/tyapi/openapi.yaml, tyapi's API description → src/model/api.ts: the type of every route's body and
// answer (docs/PLAN.md §5, phase 1), which src/api.ts's client is typed by.
//
//   node scripts/gen-api.ts           write the file
//   node scripts/gen-api.ts --check   fail if the file is not what this would write
//
// The check runs first in `pnpm build`, so a field tyapi renames fails dw's build where dw uses it.

import { readFileSync, writeFileSync } from 'node:fs'
import openapiTS, { astToString } from 'openapi-typescript'

const root = new URL('../', import.meta.url)
const OUT = new URL('src/model/api.ts', root)
const HEADER = '// Generated by scripts/gen-api.ts from vendor/tyapi/openapi.yaml (tyapi\'s API description). Do not edit.\n' +
  '// Regenerate with `pnpm gen:api`.\n\n'

const text = HEADER + astToString(await openapiTS(new URL('vendor/tyapi/openapi.yaml', root)))

if (process.argv.includes('--check')) {
  let current = ''
  try {
    current = readFileSync(OUT, 'utf8')
  } catch {
    // missing: reported below
  }
  if (current !== text) {
    console.error('src/model/api.ts is not what vendor/tyapi/openapi.yaml makes: run `pnpm gen:api`')
    process.exit(1)
  }
} else {
  writeFileSync(OUT, text)
  console.log('wrote src/model/api.ts')
}
